// Builds site-worker/index.js: a single Cloudflare Worker that serves the static site in public/ with its own headers.
// Used when assets cannot be uploaded with the assets API (e.g. from an API-only session). Run `npm run build` first.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, extname, relative } from 'node:path';
const root = 'public';
const types = { '.html': 'text/html; charset=utf-8', '.json': 'application/json; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.png': 'image/png', '.css': 'text/css; charset=utf-8' };
const files = {};
(function walk(d) {
  for (const n of readdirSync(d)) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (n === '_headers') continue;
    const ext = extname(n); const buf = readFileSync(p);
    files['/' + relative(root, p)] = { t: types[ext] || 'application/octet-stream', b: ext === '.png', d: ext === '.png' ? buf.toString('base64') : buf.toString('utf8') };
  }
})(root);
const code = `// GENERATED by scripts/build-site-worker.js from public/. Do not edit.
const FILES = ${JSON.stringify(files)};
const SECURITY = {
  'x-content-type-options': 'nosniff', 'x-frame-options': 'DENY', 'referrer-policy': 'strict-origin-when-cross-origin',
  'permissions-policy': 'camera=(), microphone=(), geolocation=(), payment=()', 'strict-transport-security': 'max-age=31536000; includeSubDomains',
  'content-security-policy': "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; form-action 'self' https://duckduckgo.com; frame-ancestors 'none'; base-uri 'none'",
};
const body = (f) => f.b ? Uint8Array.from(atob(f.d), (c) => c.charCodeAt(0)) : f.d;
export function route(pathname) {
  let p = pathname;
  if (p.endsWith('/')) p += 'index.html';
  if (FILES[p]) return { status: 200, file: FILES[p], path: p };
  if (FILES[p + '/index.html']) return { status: 301, location: p + '/' };
  return { status: 404, file: FILES['/404.html'], path: '/404.html' };
}
export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: { allow: 'GET, HEAD' } });
    const url = new URL(request.url);
    const r = route(url.pathname);
    const h = new Headers(SECURITY);
    if (r.status === 301) { h.set('location', r.location + url.search); return new Response(null, { status: 301, headers: h }); }
    h.set('content-type', r.file.t);
    h.set('cache-control', r.path === '/sw.js' ? 'no-cache' : r.path.startsWith('/icons/') ? 'public, max-age=86400' : 'public, max-age=300');
    return new Response(request.method === 'HEAD' ? null : body(r.file), { status: r.status, headers: h });
  },
};
`;
writeFileSync('site-worker/index.js', code);
console.log('site-worker/index.js', code.length, 'bytes,', Object.keys(files).length, 'files');
