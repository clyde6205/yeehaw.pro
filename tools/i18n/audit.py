#!/usr/bin/env python3
"""Per-language translation audit -> docs/TRANSLATION_AUDIT.md. Heuristic, NOT a quality review:
counts strings identical to English, strings lacking the target script, and shows the identical ones so a human can judge."""
import json, re, unicodedata, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
en = json.loads((ROOT/'tools/i18n/en.json').read_text('utf-8'))
NAMES = {'es':'Spanish','pt':'Portuguese (BR)','id':'Indonesian','fil':'Filipino','ru':'Russian','hi':'Hindi','bn':'Bengali','ur':'Urdu','ar':'Arabic','zh-CN':'Chinese (Simplified)'}
SCRIPT = {'hi':'DEVANAGARI','bn':'BENGALI','ar':'ARABIC','ur':'ARABIC','ru':'CYRILLIC','zh-CN':'CJK'}
STRIP = re.compile(r'%\d?\$?[sdf]|%%|YeeHaw|WhatsApp|Messenger|Telegram|Viber|SMS|OK|Pro|QR|Android|URL|HTTPS?|DNS')
rows = ["# Translation audit (generated by tools/i18n/audit.py)", "",
        "Heuristic only. Every language is MACHINE TRANSLATION and has NOT been reviewed by a native speaker.", "",
        "| Language | Strings | Differ from English | Identical to English | Missing target script |", "|---|---|---|---|---|"]
detail = []
for code, name in NAMES.items():
    d = json.loads((ROOT/f'tools/i18n/{code}.json').read_text('utf-8'))
    same = [k for k in en if d.get(k) == en[k]]
    miss = []
    if code in SCRIPT:
        for k, v in d.items():
            letters = [c for c in STRIP.sub('', v) if c.isalpha()]
            if letters and not any(SCRIPT[code] in unicodedata.name(c, '') for c in letters): miss.append(k)
    rows.append(f"| {name} ({code}) | {len(d)} | {len(d)-len(same)} | {len(same)} | {len(miss)} |")
    detail.append(f"- **{code}** identical: " + (', '.join(f"`{k}`" for k in same) or 'none') + (f"; no target script: {', '.join(f'`{k}`' for k in miss)}" if miss else ''))
rows += ["", "Identical strings are mostly brand names (YeeHaw Pro, WhatsApp, Messenger, Telegram, Viber, SMS) and loanwords that are the normal word in that language (e.g. 'Offline', 'Apps', 'OK'). Review list:", ""] + detail
(ROOT/'docs/TRANSLATION_AUDIT.md').write_text('\n'.join(rows)+'\n', 'utf-8')
print('\n'.join(rows[:16]))
